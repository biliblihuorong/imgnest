/** 返回 audit.actions 下的文案键，未知动作返回 null。 */
export function auditActionKey(method: string, route: string): string | null {
  const native = route.startsWith("/api/v2/") ? `/api/${route.slice("/api/v2/".length)}` : route;
  return ACTIONS[`${method} ${native}`] ?? null;
}
